-- 0029 · 知识星球同步频率调整：每 10 分钟一次（排除 00:00-06:00）
--
-- 将 zsxq_sync 任务从「每小时 20 分」改为「白天/晚间每 10 分钟」抓取：
--   */10 6-23 * * *  => 每天 06:00:00 起至 23:50:00，每 10 分钟；00:00-05:59 不执行。
-- 同时把未租出的任务 next_run_at 设为当前时间，便于发布后尽快按新频率运行（实际下次执行受 cron 约束）。
-- 幂等：重复执行仅覆盖为相同 cron/时间逻辑；向后兼容（仅改数据）。

UPDATE job
SET cron = '*/10 6-23 * * *',
    next_run_at = CAST(strftime('%s', 'now') AS INTEGER) * 1000
WHERE type = 'zsxq_sync' AND status != 'leased';
